ALTER TABLE sale_items ADD CONSTRAINT sale_items_sale_company_fk FOREIGN KEY (sale_id, company_id) REFERENCES sales(id, company_id);
ALTER TABLE sale_items ADD CONSTRAINT sale_items_product_company_fk FOREIGN KEY (product_id, company_id) REFERENCES products(id, company_id);
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_product_company_fk FOREIGN KEY (product_id, company_id) REFERENCES products(id, company_id);
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_sale_company_fk FOREIGN KEY (sale_id, company_id) REFERENCES sales(id, company_id);
