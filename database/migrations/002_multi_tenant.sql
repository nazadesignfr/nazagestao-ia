BEGIN;
ALTER TABLE company ALTER COLUMN id DROP DEFAULT;
ALTER TABLE company ALTER COLUMN id TYPE BIGINT;
ALTER TABLE company ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('company', 'id'), GREATEST(COALESCE((SELECT MAX(id) FROM company), 1), 1), true);

CREATE TABLE IF NOT EXISTS user_companies (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  company_id BIGINT NOT NULL REFERENCES company(id) ON DELETE CASCADE,
  role VARCHAR(20) NOT NULL DEFAULT 'operator' CHECK (role IN ('admin', 'operator')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, company_id)
);
INSERT INTO user_companies (user_id, company_id, role)
SELECT id, 1, CASE WHEN role = 'admin' THEN 'admin' ELSE 'operator' END FROM users
ON CONFLICT (user_id, company_id) DO NOTHING;

ALTER TABLE customers ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);
ALTER TABLE products ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);
ALTER TABLE sales ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);
ALTER TABLE sale_items ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);
ALTER TABLE stock_movements ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);
ALTER TABLE financial_entries ADD COLUMN IF NOT EXISTS company_id BIGINT REFERENCES company(id);

UPDATE customers SET company_id=1 WHERE company_id IS NULL;
UPDATE products SET company_id=1 WHERE company_id IS NULL;
UPDATE sales SET company_id=1 WHERE company_id IS NULL;
UPDATE sale_items si SET company_id=s.company_id FROM sales s WHERE si.sale_id=s.id AND si.company_id IS NULL;
UPDATE stock_movements sm SET company_id=p.company_id FROM products p WHERE sm.product_id=p.id AND sm.company_id IS NULL;
UPDATE financial_entries SET company_id=1 WHERE company_id IS NULL;

ALTER TABLE customers ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE products ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE sales ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE sale_items ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE stock_movements ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE financial_entries ALTER COLUMN company_id SET NOT NULL;

ALTER TABLE products DROP CONSTRAINT IF EXISTS products_sku_key;
CREATE UNIQUE INDEX IF NOT EXISTS idx_products_company_sku ON products(company_id, sku) WHERE sku IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_customers_company ON customers(company_id, name);
CREATE INDEX IF NOT EXISTS idx_products_company ON products(company_id, name);
CREATE INDEX IF NOT EXISTS idx_sales_company_created ON sales(company_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sale_items_company_sale ON sale_items(company_id, sale_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_company_created ON stock_movements(company_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_financial_company_due ON financial_entries(company_id, status, due_date);
CREATE INDEX IF NOT EXISTS idx_user_companies_company ON user_companies(company_id, user_id);

ALTER TABLE customers ADD CONSTRAINT customers_id_company_unique UNIQUE (id, company_id);
ALTER TABLE products ADD CONSTRAINT products_id_company_unique UNIQUE (id, company_id);
ALTER TABLE sales ADD CONSTRAINT sales_id_company_unique UNIQUE (id, company_id);
